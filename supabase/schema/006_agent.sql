-- Remote control of the Granko Recorder running next to CS2: the page queues jobs ("stand here,
-- look there, send me a screenshot"), the recorder polls for them, runs them in the game and
-- posts the result back. Everything is key-gated like the playbook.
-- Apply with:
--   supabase db query --linked --workdir E:/Projects/WeedOut -f E:/Projects/CsCoach/supabase/schema/006_agent.sql

-- One row: the recorder's heartbeat (online when seen in the last few seconds) and current map.
create table cs.agent (
    id int primary key default 1 check (id = 1),
    seen_at timestamptz,
    map text,
    info jsonb
);

create table cs.agent_jobs (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    kind text not null check (kind in ('teleport')),
    -- teleport: {map, at: {x, y, level}, look: {x, y} | null} in radar fractions
    payload jsonb not null,
    status text not null default 'new' check (status in ('new', 'taken', 'done', 'error')),
    -- done: {image, setpos, z, map}; error: {error}
    result jsonb,
    taken_at timestamptz,
    done_at timestamptz,
    created_by uuid references cs.members on delete set null
);
create index agent_jobs_new_idx on cs.agent_jobs (created_at) where status = 'new';

alter table cs.agent enable row level security;
alter table cs.agent_jobs enable row level security;
grant all on cs.agent, cs.agent_jobs to service_role;

create or replace function cs.agent_submit(k text, p_kind text, p_payload jsonb, p_by uuid) returns bigint
language plpgsql security definer set search_path = '' as $$
declare
    rid bigint;
begin
    perform cs.require_key(k);
    insert into cs.agent_jobs (kind, payload, created_by) values (p_kind, p_payload, p_by) returning id into rid;
    return rid;
end;
$$;

create or replace function cs.agent_job(k text, job_id bigint) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
    perform cs.require_key(k);
    return (select to_jsonb(j) from cs.agent_jobs j where j.id = job_id);
end;
$$;

create or replace function cs.agent_status(k text) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
    perform cs.require_key(k);
    return (select to_jsonb(a) || jsonb_build_object('online', a.seen_at > now() - interval '6 seconds') from cs.agent a);
end;
$$;

-- Recorder side: heartbeat + take the oldest fresh job. Jobs nobody picked up within two minutes
-- are dropped, so a page left clicking while the PC was off doesn't replay later.
create or replace function cs.agent_take(k text, p_map text, p_info jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
    j cs.agent_jobs;
begin
    perform cs.require_key(k);
    insert into cs.agent (id, seen_at, map, info) values (1, now(), p_map, p_info)
    on conflict (id) do update set seen_at = now(), map = excluded.map, info = excluded.info;
    update cs.agent_jobs set status = 'error', result = '{"error": "PC nie odebrał zadania"}', done_at = now()
    where status = 'new' and created_at < now() - interval '2 minutes';
    select * into j from cs.agent_jobs where status = 'new' order by created_at limit 1 for update skip locked;
    if j.id is null then
        return null;
    end if;
    update cs.agent_jobs set status = 'taken', taken_at = now() where id = j.id returning * into j;
    return to_jsonb(j);
end;
$$;

create or replace function cs.agent_finish(k text, job_id bigint, ok boolean, p_result jsonb) returns void
language plpgsql security definer set search_path = '' as $$
begin
    perform cs.require_key(k);
    update cs.agent_jobs set status = case when ok then 'done' else 'error' end, result = p_result, done_at = now()
    where id = job_id;
end;
$$;

revoke execute on function cs.agent_submit(text, text, jsonb, uuid), cs.agent_job(text, bigint), cs.agent_status(text),
    cs.agent_take(text, text, jsonb), cs.agent_finish(text, bigint, boolean, jsonb) from public;
grant execute on function cs.agent_submit(text, text, jsonb, uuid), cs.agent_job(text, bigint), cs.agent_status(text),
    cs.agent_take(text, text, jsonb), cs.agent_finish(text, bigint, boolean, jsonb) to anon, authenticated, service_role;
