-- CS Coach: rounds, timings and personal stats from CS2 Game State Integration.
--
-- Lives in its own `cs` schema inside the "WeedOut" Supabase project (the free plan allows
-- only two projects). Apply with:
--   supabase db query --linked --workdir E:/Projects/WeedOut -f E:/Projects/CsCoach/supabase/schema/001_cs.sql
-- The `cs` schema must also be listed in [api] schemas of WeedOut's supabase/config.toml.
--
-- Each player's game POSTs its state to the `cs-gsi` edge function, which checks the team token
-- and hands the payload to cs.ingest(). GSI only describes the local player (and, while dead, the
-- player being spectated), so every row here is per player; the web page groups the five players'
-- rows into one team match by map and start time.

create schema if not exists cs;
grant usage on schema cs to anon, authenticated, service_role;

create table cs.players (
    steamid text primary key,
    name text,
    first_seen timestamptz not null default now(),
    last_seen timestamptz not null default now()
);

create table cs.matches (
    id bigint generated by default as identity primary key,
    steamid text not null references cs.players on delete cascade,
    map text not null,
    mode text,
    status text not null default 'live' check (status in ('live', 'finished', 'abandoned')),
    started_at timestamptz not null,
    ended_at timestamptz,
    last_update timestamptz not null,
    -- Side at the last own update, i.e. the side the match ended on.
    team text,
    score_ct int not null default 0,
    score_t int not null default 0,
    kills int,
    assists int,
    deaths int,
    mvps int,
    score int,
    rounds_recorded int not null default 0,
    -- The round in progress; written to cs.rounds when the score says it has ended.
    cur_round int,
    cur_round_started_at timestamptz,
    cur_team text,
    cur_money_start int,
    cur_money_after_buy int,
    cur_equip_value int,
    cur_kills int,
    cur_headshots int,
    cur_damage int,
    cur_health int
);
create index matches_player_idx on cs.matches (steamid, last_update desc);
create index matches_started_idx on cs.matches (started_at desc);

create table cs.rounds (
    match_id bigint not null references cs.matches on delete cascade,
    round_no int not null,
    steamid text not null references cs.players on delete cascade,
    winner text,
    -- GSI's reason, e.g. ct_win_elimination, t_win_bomb, ct_win_defuse, ct_win_time.
    win_reason text,
    team text,
    won boolean,
    started_at timestamptz,
    ended_at timestamptz,
    money_start int,
    money_after_buy int,
    equip_value int,
    kills int,
    headshots int,
    damage int,
    survived boolean,
    primary key (match_id, round_no)
);

-- Latest payload per player, for the "playing now" strip.
create table cs.live (
    steamid text primary key references cs.players on delete cascade,
    received_at timestamptz not null default now(),
    state jsonb not null
);

alter table cs.players enable row level security;
alter table cs.matches enable row level security;
alter table cs.rounds enable row level security;
alter table cs.live enable row level security;
create policy "read" on cs.players for select using (true);
create policy "read" on cs.matches for select using (true);
create policy "read" on cs.rounds for select using (true);
create policy "read" on cs.live for select using (true);
grant select on all tables in schema cs to anon, authenticated;
grant all on all tables in schema cs to service_role;

create or replace function cs.ingest(p jsonb) returns text
language plpgsql security definer set search_path = '' as $$
declare
    me text := p #>> '{provider,steamid}';
    ts timestamptz := coalesce(to_timestamp((p #>> '{provider,timestamp}')::double precision), now());
    -- While dead, `player` is whoever we spectate, so personal stats only come from own payloads.
    own boolean := (p #>> '{player,steamid}') is not distinct from (p #>> '{provider,steamid}');
    map_name text := p #>> '{map,name}';
    map_phase text := p #>> '{map,phase}';
    round_phase text := p #>> '{round,phase}';
    st jsonb := p #> '{player,state}';
    ms jsonb := p #> '{player,match_stats}';
    m cs.matches;
    new_ct int;
    new_t int;
    rounds_done int;
    reason text;
    winner text;
begin
    if me is null then
        return 'no provider';
    end if;
    perform pg_advisory_xact_lock(hashtext('cs:' || me));

    insert into cs.players (steamid, name, last_seen)
    values (me, case when own then p #>> '{player,name}' end, now())
    on conflict (steamid) do update set last_seen = now(), name = coalesce(excluded.name, cs.players.name);

    insert into cs.live (steamid, received_at, state)
    values (me, now(), p - 'auth' - 'previously' - 'added')
    on conflict (steamid) do update set received_at = excluded.received_at, state = excluded.state;

    if map_name is null or map_phase is null or map_phase = 'warmup' then
        return 'idle';
    end if;

    new_ct := coalesce((p #>> '{map,team_ct,score}')::int, 0);
    new_t := coalesce((p #>> '{map,team_t,score}')::int, 0);
    rounds_done := new_ct + new_t;

    select * into m from cs.matches
    where steamid = me and map = map_name and status <> 'abandoned' and last_update > ts - interval '20 minutes'
    order by last_update desc limit 1;

    if m.id is not null and m.status = 'finished' then
        -- The scoreboard after the last round keeps sending gameover; anything else is a new game.
        if map_phase = 'gameover' then
            if own then
                update cs.matches set
                    kills = (ms ->> 'kills')::int,
                    assists = (ms ->> 'assists')::int,
                    deaths = (ms ->> 'deaths')::int,
                    mvps = (ms ->> 'mvps')::int,
                    score = (ms ->> 'score')::int
                where id = m.id;
            end if;
            return 'finished';
        end if;
        m := null;
    elsif m.id is not null and rounds_done < m.rounds_recorded then
        -- Score went back down: a new game on the same map.
        m := null;
    end if;

    if m.id is null then
        update cs.matches set status = 'abandoned', ended_at = last_update where steamid = me and status = 'live';
        insert into cs.matches (steamid, map, mode, started_at, last_update)
        values (me, map_name, p #>> '{map,mode}', ts, ts)
        returning * into m;
    end if;

    -- Freezetime and live belong to the round after the ones already scored; 'over' keeps the
    -- round it ended, so exit frags still count for it.
    if round_phase in ('freezetime', 'live') and m.cur_round is distinct from rounds_done + 1 then
        m.cur_round := rounds_done + 1;
        m.cur_round_started_at := null;
        m.cur_money_start := null;
        m.cur_money_after_buy := null;
        m.cur_equip_value := null;
        m.cur_kills := null;
        m.cur_headshots := null;
        m.cur_damage := null;
        m.cur_health := null;
    end if;
    if round_phase = 'live' and m.cur_round_started_at is null then
        m.cur_round_started_at := ts;
    end if;

    if own and m.cur_round is not null and round_phase in ('freezetime', 'live', 'over') then
        if round_phase = 'freezetime' then
            m.cur_money_start := coalesce(m.cur_money_start, (st ->> 'money')::int);
            m.cur_equip_value := (st ->> 'equip_value')::int;
        elsif round_phase = 'live' and m.cur_money_after_buy is null then
            m.cur_money_after_buy := (st ->> 'money')::int;
            m.cur_equip_value := (st ->> 'equip_value')::int;
        end if;
        m.cur_team := p #>> '{player,team}';
        m.cur_kills := (st ->> 'round_kills')::int;
        m.cur_headshots := (st ->> 'round_killhs')::int;
        m.cur_damage := (st ->> 'round_totaldmg')::int;
        m.cur_health := (st ->> 'health')::int;
    end if;

    for k in m.rounds_recorded + 1 .. rounds_done loop
        reason := p #>> array['map', 'round_wins', k::text];
        winner := case
            when reason like 'ct\_%' then 'CT'
            when reason like 't\_%' then 'T'
            -- No reason sent: when exactly one round ended, the side whose score went up won it.
            when rounds_done = m.rounds_recorded + 1 and new_ct > m.score_ct then 'CT'
            when rounds_done = m.rounds_recorded + 1 and new_t > m.score_t then 'T'
        end;
        insert into cs.rounds (match_id, round_no, steamid, winner, win_reason, ended_at)
        values (m.id, k, me, winner, reason, ts)
        on conflict do nothing;
    end loop;
    m.rounds_recorded := greatest(m.rounds_recorded, rounds_done);

    if m.cur_round is not null and m.cur_round <= m.rounds_recorded then
        update cs.rounds r set
            team = m.cur_team,
            won = (r.winner = m.cur_team),
            started_at = m.cur_round_started_at,
            money_start = m.cur_money_start,
            money_after_buy = m.cur_money_after_buy,
            equip_value = m.cur_equip_value,
            kills = m.cur_kills,
            headshots = m.cur_headshots,
            damage = m.cur_damage,
            survived = m.cur_health > 0
        where r.match_id = m.id and r.round_no = m.cur_round;
    end if;

    if own then
        m.team := p #>> '{player,team}';
        m.kills := (ms ->> 'kills')::int;
        m.assists := (ms ->> 'assists')::int;
        m.deaths := (ms ->> 'deaths')::int;
        m.mvps := (ms ->> 'mvps')::int;
        m.score := (ms ->> 'score')::int;
    end if;
    if map_phase = 'gameover' then
        m.status := 'finished';
        m.ended_at := coalesce(m.ended_at, ts);
    end if;

    update cs.matches set
        mode = coalesce(p #>> '{map,mode}', m.mode),
        status = m.status,
        ended_at = m.ended_at,
        last_update = ts,
        team = m.team,
        score_ct = new_ct,
        score_t = new_t,
        kills = m.kills,
        assists = m.assists,
        deaths = m.deaths,
        mvps = m.mvps,
        score = m.score,
        rounds_recorded = m.rounds_recorded,
        cur_round = m.cur_round,
        cur_round_started_at = m.cur_round_started_at,
        cur_team = m.cur_team,
        cur_money_start = m.cur_money_start,
        cur_money_after_buy = m.cur_money_after_buy,
        cur_equip_value = m.cur_equip_value,
        cur_kills = m.cur_kills,
        cur_headshots = m.cur_headshots,
        cur_damage = m.cur_damage,
        cur_health = m.cur_health
    where id = m.id;

    return 'ok';
end;
$$;

revoke execute on function cs.ingest(jsonb) from public, anon, authenticated;
grant execute on function cs.ingest(jsonb) to service_role;
