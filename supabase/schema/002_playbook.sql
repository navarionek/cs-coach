-- CS Coach playbook: team members, grenade lineups, tactics and live round calls.
-- Apply with:
--   supabase db query --linked --workdir E:/Projects/WeedOut -f E:/Projects/CsCoach/supabase/schema/002_playbook.sql
-- The team key is not in git; set (or rotate) it with:
--   insert into cs.team_secret (key_hash) values (encode(sha256(convert_to('<key>', 'UTF8')), 'hex'))
--   on conflict (id) do update set key_hash = excluded.key_hash;
--
-- The site and repo are public, so members, lineups and tactics are not readable through the API
-- at all: everything goes through security definer functions that check the team key. Only
-- cs.calls (which tactic was called for which round) is public, because every player's page
-- follows it over Realtime.

create table cs.team_secret (
    id int primary key default 1 check (id = 1),
    key_hash text not null
);

create table cs.members (
    id uuid primary key default gen_random_uuid(),
    name text not null check (btrim(name) <> ''),
    steamid text unique,
    color text,
    created_at timestamptz not null default now()
);

create table cs.lineups (
    id uuid primary key default gen_random_uuid(),
    map text not null,
    side text not null check (side in ('T', 'CT', 'any')),
    nade text not null check (nade in ('smoke', 'flash', 'molotov', 'he', 'decoy')),
    title text not null check (btrim(title) <> ''),
    -- Where it lands and where it's thrown from, as callouts.
    target text,
    position text,
    throw text,
    description text,
    -- [{path, caption}] in the cs-lineups storage bucket; caption is pos | aim | result | other.
    images jsonb not null default '[]',
    video_url text,
    created_by uuid references cs.members on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table cs.tactics (
    id uuid primary key default gen_random_uuid(),
    map text not null,
    side text not null check (side in ('T', 'CT')),
    name text not null check (btrim(name) <> ''),
    kind text not null default 'any' check (kind in ('pistol', 'eco', 'force', 'full', 'any')),
    summary text,
    notes text,
    -- [{name, member_id, position, task, lineups: [lineup id]}], one entry per player slot.
    roles jsonb not null default '[]',
    archived boolean not null default false,
    created_by uuid references cs.members on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- The tactic picked for a round. One per map + round at a time; cs.ingest() fills in `won`
-- when the round ends, which is what the suggestions learn from.
create table cs.calls (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    map text not null,
    side text not null check (side in ('T', 'CT')),
    round_no int not null,
    tactic_id uuid not null references cs.tactics on delete cascade,
    called_by uuid references cs.members on delete set null,
    auto boolean not null default false,
    won boolean
);
create index calls_round_idx on cs.calls (map, round_no, created_at desc);
create index calls_tactic_idx on cs.calls (tactic_id) where won is not null;

alter table cs.team_secret enable row level security;
alter table cs.members enable row level security;
alter table cs.lineups enable row level security;
alter table cs.tactics enable row level security;
alter table cs.calls enable row level security;
create policy "read" on cs.calls for select using (true);
grant select on cs.calls to anon, authenticated;
grant all on cs.team_secret, cs.members, cs.lineups, cs.tactics, cs.calls to service_role;
alter publication supabase_realtime add table cs.calls;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('cs-lineups', 'cs-lineups', true, 5242880, array['image/webp', 'image/jpeg', 'image/png'])
on conflict (id) do nothing;

create or replace function cs.check_key(k text) returns boolean
language sql stable security definer set search_path = '' as $$
    select exists (
        select 1 from cs.team_secret
        where key_hash = encode(sha256(convert_to(coalesce(k, ''), 'UTF8')), 'hex')
    );
$$;

create or replace function cs.require_key(k text) returns void
language plpgsql stable security definer set search_path = '' as $$
begin
    if not cs.check_key(k) then
        raise exception 'Złe hasło drużyny' using errcode = '28000';
    end if;
end;
$$;

create or replace function cs.playbook(k text) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
    perform cs.require_key(k);
    return jsonb_build_object(
        'members', coalesce((select jsonb_agg(to_jsonb(m) order by m.created_at) from cs.members m), '[]'),
        'tactics', coalesce((select jsonb_agg(to_jsonb(t) order by t.name) from cs.tactics t), '[]'),
        'lineups', coalesce((select jsonb_agg(to_jsonb(l) order by l.title) from cs.lineups l), '[]')
    );
end;
$$;

create or replace function cs.save_member(k text, m jsonb) returns uuid
language plpgsql security definer set search_path = '' as $$
declare
    rid uuid := nullif(m ->> 'id', '')::uuid;
begin
    perform cs.require_key(k);
    if rid is null then
        insert into cs.members (name, steamid, color)
        values (btrim(m ->> 'name'), nullif(m ->> 'steamid', ''), m ->> 'color')
        returning id into rid;
    else
        update cs.members set
            name = btrim(m ->> 'name'),
            steamid = nullif(m ->> 'steamid', ''),
            color = m ->> 'color'
        where id = rid;
    end if;
    return rid;
end;
$$;

create or replace function cs.delete_member(k text, member_id uuid) returns void
language plpgsql security definer set search_path = '' as $$
begin
    perform cs.require_key(k);
    delete from cs.members where id = member_id;
end;
$$;

create or replace function cs.save_lineup(k text, l jsonb) returns uuid
language plpgsql security definer set search_path = '' as $$
declare
    rid uuid := nullif(l ->> 'id', '')::uuid;
begin
    perform cs.require_key(k);
    if rid is null then
        insert into cs.lineups (map, side, nade, title, target, position, throw, description, images, video_url, created_by)
        values (
            l ->> 'map', l ->> 'side', l ->> 'nade', btrim(l ->> 'title'), l ->> 'target', l ->> 'position',
            l ->> 'throw', l ->> 'description', coalesce(l -> 'images', '[]'), nullif(l ->> 'video_url', ''),
            nullif(l ->> 'created_by', '')::uuid
        )
        returning id into rid;
    else
        update cs.lineups set
            map = l ->> 'map',
            side = l ->> 'side',
            nade = l ->> 'nade',
            title = btrim(l ->> 'title'),
            target = l ->> 'target',
            position = l ->> 'position',
            throw = l ->> 'throw',
            description = l ->> 'description',
            images = coalesce(l -> 'images', '[]'),
            video_url = nullif(l ->> 'video_url', ''),
            updated_at = now()
        where id = rid;
    end if;
    return rid;
end;
$$;

-- Returns the deleted lineup's images so the page can remove the files from storage.
create or replace function cs.delete_lineup(k text, lineup_id uuid) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
    imgs jsonb;
begin
    perform cs.require_key(k);
    delete from cs.lineups where id = lineup_id returning images into imgs;
    return coalesce(imgs, '[]');
end;
$$;

create or replace function cs.save_tactic(k text, t jsonb) returns uuid
language plpgsql security definer set search_path = '' as $$
declare
    rid uuid := nullif(t ->> 'id', '')::uuid;
begin
    perform cs.require_key(k);
    if rid is null then
        insert into cs.tactics (map, side, name, kind, summary, notes, roles, archived, created_by)
        values (
            t ->> 'map', t ->> 'side', btrim(t ->> 'name'), coalesce(t ->> 'kind', 'any'), t ->> 'summary',
            t ->> 'notes', coalesce(t -> 'roles', '[]'), coalesce((t ->> 'archived')::boolean, false),
            nullif(t ->> 'created_by', '')::uuid
        )
        returning id into rid;
    else
        update cs.tactics set
            map = t ->> 'map',
            side = t ->> 'side',
            name = btrim(t ->> 'name'),
            kind = coalesce(t ->> 'kind', 'any'),
            summary = t ->> 'summary',
            notes = t ->> 'notes',
            roles = coalesce(t -> 'roles', '[]'),
            archived = coalesce((t ->> 'archived')::boolean, false),
            updated_at = now()
        where id = rid;
    end if;
    return rid;
end;
$$;

-- Calls a tactic for a round. An auto call (the page's own suggestion) only goes in when nobody
-- has called this round yet, so the five pages racing each other agree on the first one; a
-- manual call always replaces whatever was there.
create or replace function cs.make_call(
    k text, p_map text, p_side text, p_round int, p_tactic uuid, p_by uuid, p_auto boolean
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
    existing cs.calls;
    r cs.calls;
begin
    perform cs.require_key(k);
    perform pg_advisory_xact_lock(hashtext('cs-call:' || p_map));
    select * into existing from cs.calls
    where map = p_map and round_no = p_round and created_at > now() - interval '4 minutes'
    order by created_at desc limit 1;
    -- A call made for the wrong side (sides swapped at half time) doesn't count.
    if p_auto and existing.id is not null and existing.side = p_side then
        return to_jsonb(existing);
    end if;
    delete from cs.calls where map = p_map and round_no = p_round and created_at > now() - interval '4 minutes';
    insert into cs.calls (map, side, round_no, tactic_id, called_by, auto)
    values (p_map, p_side, p_round, p_tactic, p_by, p_auto)
    returning * into r;
    return to_jsonb(r);
end;
$$;

revoke execute on function cs.check_key(text), cs.require_key(text), cs.playbook(text), cs.save_member(text, jsonb),
    cs.delete_member(text, uuid), cs.save_lineup(text, jsonb), cs.delete_lineup(text, uuid),
    cs.save_tactic(text, jsonb), cs.make_call(text, text, text, int, uuid, uuid, boolean) from public;
grant execute on function cs.check_key(text), cs.require_key(text), cs.playbook(text), cs.save_member(text, jsonb),
    cs.delete_member(text, uuid), cs.save_lineup(text, jsonb), cs.delete_lineup(text, uuid),
    cs.save_tactic(text, jsonb), cs.make_call(text, text, text, int, uuid, uuid, boolean)
    to anon, authenticated, service_role;
